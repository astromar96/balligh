const DICTS: Record<Language, Record<MessageKey, string>> = { ar, en }

export type Params = Record<string, string | number>

/** Looks up a message and fills {placeholders}; numbers become Arabic-Indic digits in Arabic. */
export function translate(lang: Language, key: MessageKey, params?: Params): string {
  const template = DICTS[lang][key] ?? DICTS.ar[key] ?? key
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const v = params[name]
    if (v === undefined) return `{${name}}`
    return typeof v === 'number' ? formatNumber(lang, v) : v
  })
}

export function formatNumber(lang: Language, n: number): string {
  return lang === 'ar' ? toIndic(String(n)) : String(n)
}

/** Arabic count nouns: 1 آية · 2 آيتان · 3–10 آيات · 11+ آية. */
export function pluralAr(n: number, forms: { one: string; two: string; few: string; many: string }): string {
  const m = Math.abs(n) % 100
  if (n === 1) return forms.one
  if (n === 2) return forms.two
  if (m >= 3 && m <= 10) return forms.few
  return forms.many
}

export type CountNoun = 'ayah' | 'word' | 'image'

const AR_FORMS: Record<CountNoun, { one: string; two: string; few: string; many: string }> = {
  ayah: { one: 'آية', two: 'آيتان', few: 'آيات', many: 'آية' },
  word: { one: 'كلمة', two: 'كلمتان', few: 'كلمات', many: 'كلمة' },
  image: { one: 'صورة', two: 'صورتان', few: 'صور', many: 'صورة' },
}

const EN_NOUNS: Record<CountNoun, [string, string]> = { ayah: ['verse', 'verses'], word: ['word', 'words'], image: ['image', 'images'] }

export function countLabel(lang: Language, n: number, noun: CountNoun): string {
  if (lang === 'en') return `${n} ${EN_NOUNS[noun][n === 1 ? 0 : 1]}`
  const word = pluralAr(n, AR_FORMS[noun])
  if (n === 1 || n === 2) return word
  return `${toIndic(String(n))} ${word}`
}

export function isRtl(lang: Language): boolean {
  return lang === 'ar'
}

/** All keys present in both dictionaries (used by the completeness test). */
export function missingKeys(): { ar: string[]; en: string[] } {
  const keys = new Set([...Object.keys(ar), ...Object.keys(en)])
  const out = { ar: [] as string[], en: [] as string[] }
  for (const k of keys) {
    if (!(k in ar) || !(ar as Record<string, string>)[k]) out.ar.push(k)
    if (!(k in en) || !(en as Record<string, string>)[k]) out.en.push(k)
  }
  return out
}
